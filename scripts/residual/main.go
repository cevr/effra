// Command residual measures what //line directives cost a generated Go
// application and what they buy its diagnostics. For every authored example
// it lowers the native build entry twice, without source positions ("before",
// the unnamed GoApplication) and with them ("after", GoApplicationFrom), and
// records for each:
//
//   - generated main.go bytes and lowering time;
//   - cold go build seconds: the generated main and runtime packages miss
//     the build cache while the standard library stays warm, forced by a nonce
//     file in each generated package;
//   - unstripped binary bytes;
//   - the compiler's "Found IsInBounds" (bounds checks left in) and "escapes
//     to heap" lines, by the file Go attributes them to: the .ef source, the
//     generated main.go, the generated runtime, or anything else (inlined
//     standard library, <autogenerated> wrappers);
//   - go vet's verdict.
//
// Builds use ef build's flags. Samples interleave the two lowerings and
// alternate which goes first, and record the load average beside each time.
//
// Run from the repository root:
//
//	GOCACHE=<dir> GOTMPDIR=<dir> go run ./scripts/residual -work <dir> -json <file> -markdown <file>
package main

import (
	"bufio"
	"bytes"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"sort"
	"strings"
	"time"

	"effra.local/prototype/internal/compiler"
	"effra.local/prototype/internal/receipt"
)

// Attribution counts compiler diagnostic lines by the file Go names.
type Attribution struct {
	Source  int `json:"source"`
	Main    int `json:"main"`
	Runtime int `json:"runtime"`
	Other   int `json:"other"`
}

func (a Attribution) total() int { return a.Source + a.Main + a.Runtime + a.Other }

// Sample is one cold build and the load average read just before it.
type Sample struct {
	Seconds float64 `json:"seconds"`
	Load    string  `json:"load"`
}

// Variant is one lowering of an example.
type Variant struct {
	GeneratedBytes int         `json:"generatedBytes"`
	LoweringMicros []int64     `json:"loweringMicros"`
	BinaryBytes    int64       `json:"binaryBytes"`
	Samples        []Sample    `json:"samples"`
	BoundsChecks   Attribution `json:"boundsChecks"`
	Escapes        Attribution `json:"escapes"`
	Vet            string      `json:"vet"`
}

// Example is the measurement of one authored example.
type Example struct {
	Name    string   `json:"name"`
	Skipped string   `json:"skipped,omitempty"`
	Before  *Variant `json:"before,omitempty"`
	After   *Variant `json:"after,omitempty"`
	// Mismatch names a diagnostic total that differs between the lowerings:
	// directives move attribution, never the checks or escapes themselves.
	Mismatch string `json:"mismatch,omitempty"`
}

// Report is the complete measurement.
type Report struct {
	GoVersion string    `json:"goVersion"`
	Flags     []string  `json:"flags"`
	Started   string    `json:"started"`
	Examples  []Example `json:"examples"`
}

const diagnosticFlags = "-gcflags=effra.generated/...=-m -d=ssa/check_bce/debug=1"

func main() {
	pattern := flag.String("examples", "examples/*.ef", "glob of examples to measure")
	work := flag.String("work", "", "directory for generated modules and binaries (required; removed module by module)")
	samples := flag.Int("samples", 3, "cold build samples per lowering")
	lowerings := flag.Int("lowerings", 5, "lowering time samples per lowering")
	jsonOut := flag.String("json", "", "write the raw report here")
	markdownOut := flag.String("markdown", "", "write the markdown table here (default stdout)")
	flag.Parse()
	if *work == "" || *samples < 1 || *lowerings < 1 {
		flag.Usage()
		os.Exit(2)
	}
	report, err := measure(*pattern, *work, *samples, *lowerings)
	if err != nil {
		fmt.Fprintln(os.Stderr, "residual:", err)
		os.Exit(1)
	}
	if *jsonOut != "" {
		data, err := json.MarshalIndent(report, "", "  ")
		if err == nil {
			err = os.WriteFile(*jsonOut, append(data, '\n'), 0o644)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, "residual:", err)
			os.Exit(1)
		}
	}
	table := markdown(report)
	if *markdownOut == "" {
		fmt.Print(table)
	} else if err := os.WriteFile(*markdownOut, []byte(table), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "residual:", err)
		os.Exit(1)
	}
}

func measure(pattern, work string, samples, lowerings int) (*Report, error) {
	files, err := filepath.Glob(pattern)
	if err != nil || len(files) == 0 {
		return nil, fmt.Errorf("no examples match %q", pattern)
	}
	sort.Strings(files)
	version, err := exec.Command("go", "version").Output()
	if err != nil {
		return nil, fmt.Errorf("go version: %w", err)
	}
	report := &Report{GoVersion: strings.TrimSpace(string(version)), Flags: receipt.GoBuildFlags, Started: time.Now().UTC().Format(time.RFC3339)}
	if err := os.MkdirAll(work, 0o755); err != nil {
		return nil, err
	}
	for _, path := range files {
		example, err := measureExample(path, work, samples, lowerings)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		fmt.Fprintf(os.Stderr, "residual: %s done\n", example.Name)
		report.Examples = append(report.Examples, example)
	}
	return report, nil
}

func measureExample(path, work string, samples, lowerings int) (Example, error) {
	origin, err := filepath.Abs(path)
	if err != nil {
		return Example{}, err
	}
	name := filepath.Base(origin)
	example := Example{Name: name}
	text, err := os.ReadFile(origin)
	if err != nil {
		return example, err
	}
	r := compiler.CompileAt(string(text), "go", filepath.Dir(origin))
	if !r.Checked {
		example.Skipped = "does not check"
		return example, nil
	}
	if _, err := r.GoApplication(compiler.GoGenerationBuild); err != nil {
		example.Skipped = "no build entry: " + firstLine(err.Error())
		return example, nil
	}
	lower := map[string]func() (*compiler.GoApplication, error){
		"before": func() (*compiler.GoApplication, error) { return r.GoApplication(compiler.GoGenerationBuild) },
		"after": func() (*compiler.GoApplication, error) {
			return r.GoApplicationFrom(compiler.GoGenerationBuild, origin)
		},
	}
	variants := map[string]*Variant{}
	directories := map[string]string{}
	for _, label := range []string{"before", "after"} {
		variant := &Variant{}
		var application *compiler.GoApplication
		for range lowerings {
			start := time.Now()
			application, err = lower[label]()
			variant.LoweringMicros = append(variant.LoweringMicros, time.Since(start).Microseconds())
			if err != nil {
				return example, err
			}
		}
		variant.GeneratedBytes = len(application.Main)
		snapshot, err := r.GoSourceSnapshot(origin, application)
		if err != nil {
			return example, err
		}
		directory := filepath.Join(work, strings.TrimSuffix(name, ".ef"), label)
		if err := writeModule(directory, snapshot); err != nil {
			return example, err
		}
		variants[label], directories[label] = variant, directory
	}
	defer func() {
		for _, directory := range directories {
			os.RemoveAll(filepath.Dir(directory))
		}
	}()
	for _, label := range []string{"before", "after"} {
		variant, directory := variants[label], directories[label]
		if err := nonce(directory); err != nil {
			return example, err
		}
		output, err := goCommand(directory, "build", append(slices.Clone(receipt.GoBuildFlags), diagnosticFlags, "-o", os.DevNull, ".")...)
		if err != nil {
			return example, fmt.Errorf("%s diagnostic build: %v\n%s", label, err, output)
		}
		variant.BoundsChecks, variant.Escapes = attribute(output, name)
		binary := filepath.Join(directory, "app")
		if output, err := goCommand(directory, "build", append(slices.Clone(receipt.GoBuildFlags), "-o", binary, ".")...); err != nil {
			return example, fmt.Errorf("%s build: %v\n%s", label, err, output)
		}
		info, err := os.Stat(binary)
		if err != nil {
			return example, err
		}
		variant.BinaryBytes = info.Size()
		if output, err := goCommand(directory, "vet", "./..."); err != nil {
			variant.Vet = "fail: " + firstLine(string(output))
		} else {
			variant.Vet = "ok"
		}
	}
	for sample := range samples {
		order := []string{"before", "after"}
		if sample%2 == 1 {
			order = []string{"after", "before"}
		}
		for _, label := range order {
			directory := directories[label]
			if err := nonce(directory); err != nil {
				return example, err
			}
			load, _ := os.ReadFile("/proc/loadavg")
			start := time.Now()
			output, err := goCommand(directory, "build", append(slices.Clone(receipt.GoBuildFlags), "-o", filepath.Join(directory, "app"), ".")...)
			elapsed := time.Since(start).Seconds()
			if err != nil {
				return example, fmt.Errorf("%s cold build: %v\n%s", label, err, output)
			}
			variants[label].Samples = append(variants[label].Samples, Sample{Seconds: elapsed, Load: loadFields(string(load))})
		}
	}
	example.Before, example.After = variants["before"], variants["after"]
	for _, pair := range []struct {
		kind          string
		before, after Attribution
	}{{"bounds checks", example.Before.BoundsChecks, example.After.BoundsChecks}, {"escapes", example.Before.Escapes, example.After.Escapes}} {
		if pair.before.total() != pair.after.total() {
			example.Mismatch += fmt.Sprintf("%s %d before, %d after; ", pair.kind, pair.before.total(), pair.after.total())
		}
	}
	return example, nil
}

// writeModule lays out a generated module as ef build publishes it.
func writeModule(directory string, snapshot compiler.GoSourceSnapshot) error {
	files := map[string][]byte{"main.go": snapshot.Main, "go.mod": snapshot.Module}
	if len(snapshot.ModuleSum) > 0 {
		files["go.sum"] = snapshot.ModuleSum
	}
	for name, data := range snapshot.Runtime {
		files[filepath.Join("runtime", name)] = data
	}
	for name, data := range files {
		path := filepath.Join(directory, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// nonce rewrites one unused constant in each generated package, so the next
// build compiles both packages again while every standard package stays
// cached.
func nonce(directory string) error {
	value := make([]byte, 8)
	if _, err := rand.Read(value); err != nil {
		return err
	}
	text := hex.EncodeToString(value)
	for path, pkg := range map[string]string{"zz_residual_nonce.go": "main", filepath.Join("runtime", "zz_residual_nonce.go"): "effra"} {
		source := "package " + pkg + "\n\nconst residualNonce = \"" + text + "\"\n"
		if err := os.WriteFile(filepath.Join(directory, path), []byte(source), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func goCommand(directory, verb string, arguments ...string) ([]byte, error) {
	command := exec.Command("go", append([]string{verb}, arguments...)...)
	command.Dir = directory
	command.Env = append(os.Environ(), "GOFLAGS=", "GOWORK=off")
	return command.CombinedOutput()
}

// attribute counts bounds-check and escape lines of the compiler's
// diagnostic output by the file each names.
func attribute(output []byte, source string) (bounds, escapes Attribution) {
	scanner := bufio.NewScanner(bytes.NewReader(output))
	scanner.Buffer(make([]byte, 0, 64*1024), 1<<20)
	for scanner.Scan() {
		line := scanner.Text()
		var counter *Attribution
		switch {
		case strings.Contains(line, ": Found IsInBounds"):
			counter = &bounds
		case strings.Contains(line, " escapes to heap"):
			counter = &escapes
		default:
			continue
		}
		file, _, _ := strings.Cut(line, ":")
		switch {
		case file == "effra.generated/"+source:
			counter.Source++
		case file == "effra.generated/main.go":
			counter.Main++
		case strings.HasPrefix(file, "effra.generated/runtime/"):
			counter.Runtime++
		default:
			counter.Other++
		}
	}
	return bounds, escapes
}

func loadFields(load string) string {
	fields := strings.Fields(load)
	if len(fields) > 3 {
		fields = fields[:3]
	}
	return strings.Join(fields, " ")
}

func firstLine(text string) string {
	line, _, _ := strings.Cut(strings.TrimSpace(text), "\n")
	return line
}

func median(values []float64) float64 {
	sorted := slices.Clone(values)
	slices.Sort(sorted)
	if len(sorted)%2 == 1 {
		return sorted[len(sorted)/2]
	}
	return (sorted[len(sorted)/2-1] + sorted[len(sorted)/2]) / 2
}

func seconds(variant *Variant) []float64 {
	values := []float64{}
	for _, sample := range variant.Samples {
		values = append(values, sample.Seconds)
	}
	return values
}

func micros(variant *Variant) []float64 {
	values := []float64{}
	for _, value := range variant.LoweringMicros {
		values = append(values, float64(value))
	}
	return values
}

func percent(before, after float64) string {
	if before == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%+.1f%%", (after-before)/before*100)
}

func timing(values []float64) string {
	return fmt.Sprintf("%.2f [%.2f-%.2f]", median(values), slices.Min(values), slices.Max(values))
}

func attribution(a Attribution) string {
	return fmt.Sprintf("%d/%d/%d/%d", a.Source, a.Main, a.Runtime, a.Other)
}

// markdown renders one row per example and a totals row. Attribution cells
// read source/main.go/runtime/other.
func markdown(report *Report) string {
	var out strings.Builder
	fmt.Fprintf(&out, "Measured with %s, flags %s, %s.\n\n", report.GoVersion, strings.Join(report.Flags, " "), report.Started)
	out.WriteString("| example | main.go bytes before / after (delta) | lowering us median before / after | cold build s median [range] before / after | binary bytes before / after (delta) | IsInBounds .ef/main.go/runtime/other before -> after | escapes .ef/main.go/runtime/other before -> after | vet after | load at samples |\n")
	out.WriteString("|---|---|---|---|---|---|---|---|---|\n")
	var totalBefore, totalAfter Variant
	var buildBefore, buildAfter []float64
	for _, example := range report.Examples {
		if example.Skipped != "" {
			fmt.Fprintf(&out, "| %s | skipped: %s | | | | | | | |\n", example.Name, example.Skipped)
			continue
		}
		before, after := example.Before, example.After
		loads := []string{}
		for _, sample := range before.Samples {
			loads = append(loads, strings.Fields(sample.Load)[0])
		}
		for _, sample := range after.Samples {
			loads = append(loads, strings.Fields(sample.Load)[0])
		}
		name := example.Name
		if example.Mismatch != "" {
			name += " (totals differ: " + strings.TrimSuffix(example.Mismatch, "; ") + ")"
		}
		fmt.Fprintf(&out, "| %s | %d / %d (%s) | %.0f / %.0f | %s / %s | %d / %d (%s) | %s -> %s | %s -> %s | %s | %s |\n",
			name,
			before.GeneratedBytes, after.GeneratedBytes, percent(float64(before.GeneratedBytes), float64(after.GeneratedBytes)),
			median(micros(before)), median(micros(after)),
			timing(seconds(before)), timing(seconds(after)),
			before.BinaryBytes, after.BinaryBytes, percent(float64(before.BinaryBytes), float64(after.BinaryBytes)),
			attribution(before.BoundsChecks), attribution(after.BoundsChecks),
			attribution(before.Escapes), attribution(after.Escapes),
			after.Vet, strings.Join(loads, ", "))
		for _, pair := range []struct{ total, variant *Variant }{{&totalBefore, before}, {&totalAfter, after}} {
			pair.total.GeneratedBytes += pair.variant.GeneratedBytes
			pair.total.BinaryBytes += pair.variant.BinaryBytes
			for _, a := range []struct{ total, variant *Attribution }{{&pair.total.BoundsChecks, &pair.variant.BoundsChecks}, {&pair.total.Escapes, &pair.variant.Escapes}} {
				a.total.Source += a.variant.Source
				a.total.Main += a.variant.Main
				a.total.Runtime += a.variant.Runtime
				a.total.Other += a.variant.Other
			}
		}
		buildBefore = append(buildBefore, median(seconds(before)))
		buildAfter = append(buildAfter, median(seconds(after)))
	}
	if len(buildBefore) > 0 {
		sum := func(values []float64) float64 {
			total := 0.0
			for _, value := range values {
				total += value
			}
			return total
		}
		fmt.Fprintf(&out, "| total | %d / %d (%s) | | %.2f / %.2f (sum of medians, %s) | %d / %d (%s) | %s -> %s | %s -> %s | | |\n",
			totalBefore.GeneratedBytes, totalAfter.GeneratedBytes, percent(float64(totalBefore.GeneratedBytes), float64(totalAfter.GeneratedBytes)),
			sum(buildBefore), sum(buildAfter), percent(sum(buildBefore), sum(buildAfter)),
			totalBefore.BinaryBytes, totalAfter.BinaryBytes, percent(float64(totalBefore.BinaryBytes), float64(totalAfter.BinaryBytes)),
			attribution(totalBefore.BoundsChecks), attribution(totalAfter.BoundsChecks),
			attribution(totalBefore.Escapes), attribution(totalAfter.Escapes))
	}
	return out.String()
}
