// A relative -work names the same directory after the process, or a go
// command it starts inside a generated module, changes directory.
func TestWorkDirectoryIsAbsolute(t *testing.T) {
	start := t.TempDir()
	t.Chdir(start)
	work, err := workDirectory(filepath.Join("relative", "work"))
	if err != nil {
		t.Fatal(err)
	}
	if !filepath.IsAbs(work) {
		t.Fatalf("work directory %q is relative", work)
	}
	t.Chdir(t.TempDir())
	if info, err := os.Stat(work); err != nil || !info.IsDir() {
		t.Fatalf("work directory %q is not found from another directory: %v", work, err)
	}
	if info, err := os.Stat(filepath.Join(start, "relative", "work")); err != nil || !info.IsDir() {
		t.Fatalf("work directory was not created under the starting directory: %v", err)
	}
}

// The compiler's diagnostic lines are attributed by the file they name: the
// source as Go reports it under -trimpath, the generated main, the generated
// runtime, or anything else. Other diagnostics are not counted.
func TestAttributeCountsBoundsChecksAndEscapesByFile(t *testing.T) {
	output := []byte(`# ergo.generated/runtime
ergo.generated/runtime/effect.go:12:7: Found IsInBounds
ergo.generated/runtime/effect.go:20:9: &x escapes to heap
# ergo.generated
ergo.generated/shop.ef:4: Found IsInBounds
ergo.generated/shop.ef:4: Found IsSliceInBounds
ergo.generated/shop.ef:9: func literal escapes to heap
ergo.generated/main.go:88:3: moved to heap: y
ergo.generated/main.go:90:14: ... argument escapes to heap
ergo.generated/other.ef:2: Found IsInBounds
<autogenerated>:1: .this does not escape
slices/zsortanyfunc.go:20:6: Found IsInBounds
`)
	bounds, escapes := attribute(output, "shop.ef")
	if want := (Attribution{Source: 1, Runtime: 1, Other: 2}); bounds != want {
		t.Errorf("bounds checks %+v, want %+v", bounds, want)
	}
	if want := (Attribution{Source: 1, Main: 1, Runtime: 1}); escapes != want {
		t.Errorf("escapes %+v, want %+v", escapes, want)
	}
}

// A source name may contain colons; it is matched whole, and a name that
// merely starts like it is not the source.
func TestAttributeMatchesSourceNamesWithColons(t *testing.T) {
	output := []byte(`ergo.generated/probe:v2.ef:4: x escapes to heap
ergo.generated/probe:v2.ef.bak:4: y escapes to heap
ergo.generated/probe:v2.ef:7: Found IsInBounds
`)
	bounds, escapes := attribute(output, "probe:v2.ef")
	if want := (Attribution{Source: 1}); bounds != want {
		t.Errorf("bounds checks %+v, want %+v", bounds, want)
	}
	if want := (Attribution{Source: 1, Other: 1}); escapes != want {
		t.Errorf("escapes %+v, want %+v", escapes, want)
	}
}

// A report from a host without load averages renders.
func TestMarkdownRendersUnavailableLoad(t *testing.T) {
	variant := func() *Variant {
		return &Variant{GeneratedBytes: 10, LoweringMicros: []int64{5}, BinaryBytes: 100, Samples: []Sample{{Seconds: 1, Load: "unavailable"}, {Seconds: 2, Load: ""}}, Vet: "ok"}
	}
	table := markdown(&Report{GoVersion: "go", Examples: []Example{{Name: "a.ef", Before: variant(), After: variant()}}})
	if !strings.Contains(table, "unavailable") {
		t.Errorf("table does not record the unavailable load:\n%s", table)
	}
}

func TestMedianAndPercent(t *testing.T) {
	if got := median([]float64{3, 1, 2}); got != 2 {
		t.Errorf("median of three = %v", got)
	}
	if got := median([]float64{4, 1, 2, 3}); got != 2.5 {
		t.Errorf("median of four = %v", got)
	}
	if got := percent(200, 230); got != "+15.0%" {
		t.Errorf("percent = %q", got)
	}
	if got := percent(0, 1); got != "n/a" {
		t.Errorf("percent of zero = %q", got)
	}
}
