import "testing"

// The compiler's diagnostic lines are attributed by the file they name: the
// source as Go reports it under -trimpath, the generated main, the generated
// runtime, or anything else. Other diagnostics are not counted.
func TestAttributeCountsBoundsChecksAndEscapesByFile(t *testing.T) {
	output := []byte(`# effra.generated/runtime
effra.generated/runtime/effect.go:12:7: Found IsInBounds
effra.generated/runtime/effect.go:20:9: &x escapes to heap
# effra.generated
effra.generated/shop.ef:4: Found IsInBounds
effra.generated/shop.ef:4: Found IsSliceInBounds
effra.generated/shop.ef:9: func literal escapes to heap
effra.generated/main.go:88:3: moved to heap: y
effra.generated/main.go:90:14: ... argument escapes to heap
effra.generated/other.ef:2: Found IsInBounds
<autogenerated>:1: .this does not escape
slices/zsortanyfunc.go:20:6: Found IsInBounds
`)
	bounds, escapes := attribute(output, "shop.ef")
	if want := (Attribution{Source: 1, Runtime: 1, Other: 2}); bounds != want {
		t.Errorf("bounds checks %+v, want %+v", bounds, want)
	}
	if want := (Attribution{Source: 1, Main: 1, Runtime: 1}); escapes != want {
		t.Errorf("escapes %+v, want %+v", escapes, want)
	}
}

func TestMedianAndPercent(t *testing.T) {
	if got := median([]float64{3, 1, 2}); got != 2 {
		t.Errorf("median of three = %v", got)
	}
	if got := median([]float64{4, 1, 2, 3}); got != 2.5 {
		t.Errorf("median of four = %v", got)
	}
	if got := percent(200, 230); got != "+15.0%" {
		t.Errorf("percent = %q", got)
	}
	if got := percent(0, 1); got != "n/a" {
		t.Errorf("percent of zero = %q", got)
	}
}
