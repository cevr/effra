//go:embed rt/rt.go
var runtimeSource string

// RuntimeSource is the rt package copied next to every emitted program.
func RuntimeSource() string { return runtimeSource }

// GoMod is the go.mod of an emitted program.
const GoMod = "module sketchgen\n\ngo 1.27\n"

// frame is the Go function being written: a declared function or the closure
// of a timeout.After block.
type frame struct {
	result   string // sketch result type, "" for none
	fallible bool
	unit     bool // a closure whose Go result is (struct{}, error) though the source has no value
}

type emitter struct {
	c       *Checked
	src     string // the source file name used in //line directives
	b       strings.Builder
	depth   int
	tmp     int
	frames  []frame
	envVal  string // expression for the env struct: env__ or a with copy
	envPtr  string
	useTime bool
	useFmt  bool
}

// Emit lowers a checked file to one Go file, main.go, in package main.
func Emit(c *Checked) (string, error) {
	e := &emitter{c: c, src: filepath.Base(c.File.Name)}
	e.types()
	e.env()
	// main comes before the first //line directive, so its lines stay main.go's.
	e.line("func main() {")
	e.line("\tt__ := rt.Root()")
	e.line("\tdefer rt.Recover()")
	e.line("\tmain__(&Env__{Console: rt.Stdout{}}, t__)")
	e.line("}")
	e.line("")
	for _, fn := range c.File.Funcs {
		e.function(fn)
	}
	for _, w := range c.File.Wires {
		e.wire(w)
	}
	imports := []string{`"sketchgen/rt"`}
	if e.useFmt {
		imports = append(imports, `"fmt"`)
	}
	if e.useTime {
		imports = append(imports, `"time"`)
	}
	head := "// Code generated by sketchc from " + e.src + ". DO NOT EDIT.\n\npackage main\n\nimport (\n\t" +
		strings.Join(imports, "\n\t") + "\n)\n\n"
	out := head + e.b.String()
	formatted, err := format.Source([]byte(out))
	if err != nil {
		return out, fmt.Errorf("emitted Go does not parse: %w", err)
	}
	return string(formatted), nil
}

func (e *emitter) line(format string, args ...any) {
	e.b.WriteString(strings.Repeat("\t", e.depth))
	fmt.Fprintf(&e.b, format, args...)
	e.b.WriteByte('\n')
}

// directive maps the next Go line to a source line. It must start in column 1.
func (e *emitter) directive(p Pos) {
	fmt.Fprintf(&e.b, "//line %s:%d\n", e.src, p.Line)
}

// Every generated name contains "__", which no source name may (S109), and
// every source value is emitted as name__l (see goLocal), so generated names,
// source values, types and functions never capture each other.
func (e *emitter) temp(prefix string) string {
	e.tmp++
	return fmt.Sprintf("%s__%d", prefix, e.tmp)
}

// isTemp reports whether v names a temporary, which Go requires to be read.
func isTemp(v string) bool { return strings.HasPrefix(v, "v__") }

// goLocal is the Go name of a source local, parameter or receiver.
func goLocal(name string) string { return name + "__l" }

func (e *emitter) goType(t string) string {
	switch t {
	case "":
		return "struct{}"
	case "duration":
		e.useTime = true
		return "time.Duration"
	case "Console", "Scheduler", "LiveScheduler":
		return "rt." + t
	}
	return t
}

func (e *emitter) zero(t string) string {
	switch t {
	case "string":
		return `""`
	case "int", "int64", "duration":
		return "0"
	case "bool":
		return "false"
	case "":
		return "struct{}{}"
	}
	if d := e.c.Types[t]; d != nil && d.Kind != kindStruct {
		return "nil"
	}
	return e.goType(t) + "{}"
}

func (e *emitter) types() {
	unions := map[string][]string{} // variant -> unions it belongs to
	for _, d := range e.c.File.Types {
		switch d.Kind {
		case kindStruct:
			e.line("type %s struct {", d.Name)
			for _, f := range d.Fields {
				e.line("\t%s %s", f.Name, e.goType(f.Type))
			}
			e.line("}")
			if e.c.ErrorTypes[d.Name] {
				e.useFmt = true
				e.line("func (e__ %s) Error() string {", d.Name)
				e.line("\ttype plain__ %s // no Error method, so Sprintf cannot recurse", d.Name)
				e.line("\treturn fmt.Sprintf(\"%s%%+v\", plain__(e__))", d.Name)
				e.line("}")
			}
		case kindCapability:
			e.line("type %s interface {", d.Name)
			for _, m := range d.Methods {
				e.line("\t%s%s", m.Name, e.signature(m, "t__ *rt.Task"))
			}
			e.line("}")
		case kindUnion:
			e.line("type %s interface{ is__%s() }", d.Name, d.Name)
			for _, v := range d.Variants {
				unions[v] = append(unions[v], d.Name)
			}
		}
		e.line("")
	}
	variants := make([]string, 0, len(unions))
	for v := range unions {
		variants = append(variants, v)
	}
	sort.Strings(variants)
	for _, v := range variants {
		for _, u := range unions[v] {
			e.line("func (%s) is__%s() {}", v, u)
		}
	}
	e.line("")
}

// env holds one field per capability. with copies it.
func (e *emitter) env() {
	e.line("type Env__ struct {")
	for _, cap := range e.c.Caps {
		e.line("\t%s %s", cap, e.goType(cap))
	}
	e.line("}")
	e.line("")
}

func (e *emitter) signature(s *Sig, hidden string) string {
	params := []string{}
	if hidden != "" {
		params = append(params, hidden)
	}
	for _, p := range s.Params {
		params = append(params, goLocal(p.Name)+" "+e.goType(p.Type))
	}
	res := ""
	switch {
	case s.Fallible && s.Result != "":
		res = " (" + e.goType(s.Result) + ", error)"
	case s.Fallible:
		res = " error"
	case s.Result != "":
		res = " " + e.goType(s.Result)
	}
	return "(" + strings.Join(params, ", ") + ")" + res
}

// function lowers a function or method. Functions take the env and the task as
// hidden parameters; methods take only the task.
func (e *emitter) function(fn *FuncDecl) {
	e.directive(fn.Pos)
	name := fn.Name
	if fn.Recv == nil && name == "main" {
		name = "main__"
	}
	if fn.Recv != nil {
		recv := fn.Recv.Type
		if fn.Recv.Name != "" {
			recv = goLocal(fn.Recv.Name) + " " + recv
		}
		e.line("func (%s) %s%s {", recv, name, e.signature(&fn.Sig, "t__ *rt.Task"))
	} else {
		e.line("func %s%s {", name, e.signature(&fn.Sig, "env__ *Env__, t__ *rt.Task"))
	}
	e.frames = []frame{{result: fn.Result, fallible: fn.Fallible}}
	e.envVal, e.envPtr = "env__", "env__"
	if fn.Recv != nil {
		// Provider methods require no capabilities (S102), so the functions they
		// call get an empty env.
		e.envVal, e.envPtr = "Env__{}", "&Env__{}"
	}
	e.depth++
	e.stmts(fn.Body.Stmts)
	switch {
	case goTerminates(fn.Body):
	case fn.Result != "":
		// A type switch over a whole union ends the function in the sketch, but
		// Go needs a default arm to see that.
		e.line("panic(\"unreachable\")")
	case fn.Fallible:
		e.line("return nil")
	}
	e.depth--
	e.line("}")
	e.line("")
}

// goTerminates is Go's terminating-statement rule for the statements we emit.
func goTerminates(b *Block) bool {
	if len(b.Stmts) == 0 {
		return false
	}
	switch s := b.Stmts[len(b.Stmts)-1].(type) {
	case *ReturnStmt:
		return true
	case *IfStmt:
		return s.Else != nil && goTerminates(s.Then) && goTerminates(s.Else)
	}
	return false
}

func wireFunc(name string) string { return "wire__" + name }

// wire emits a named wire as a function that sets its providers on an env. Its
// initializers require no capability and cannot fail (S102, S101), so it runs
// with an empty env in an infallible frame. A wire that names itself through a
// with becomes ordinary recursion, not endless emission.
func (e *emitter) wire(w *WireDecl) {
	e.directive(w.Pos)
	e.line("func %s(envc__ *Env__, t__ *rt.Task) {", wireFunc(w.Name))
	e.frames = []frame{{}}
	e.envVal, e.envPtr = "Env__{}", "&Env__{}"
	e.depth++
	for _, en := range w.Entries {
		v, _ := e.expr(en.Value)
		e.line("envc__.%s = %s", en.Cap, v)
	}
	e.depth--
	e.line("}")
	e.line("")
}

func (e *emitter) top() frame { return e.frames[len(e.frames)-1] }

// fail returns err from the current frame, or panics when the frame cannot fail.
// Only rt.Interrupted reaches an infallible frame; the checker rules out the rest.
func (e *emitter) fail(err string) {
	f := e.top()
	switch {
	case !f.fallible:
		e.line("panic(%s)", err)
	case f.unit:
		e.line("return struct{}{}, %s", err)
	case f.result == "":
		e.line("return %s", err)
	default:
		e.line("return %s, %s", e.zero(f.result), err)
	}
}

func (e *emitter) stmts(list []Stmt) {
	for _, s := range list {
		e.stmt(s)
	}
}

func (e *emitter) stmt(s Stmt) {
	e.directive(s.stmtPos())
	switch s := s.(type) {
	case *DefineStmt:
		// The checked type is spelled out, so an untyped Go constant cannot pick
		// a different type than the checker did.
		v, _ := e.expr(s.Value)
		e.line("var %s %s = %s", goLocal(s.Name), e.goType(e.c.Info[s.Value].typ), v)
	case *ReturnStmt:
		e.ret(s)
	case *IfStmt:
		cond, _ := e.expr(s.Cond)
		e.line("if %s {", cond)
		e.block(s.Then)
		if s.Else != nil {
			e.line("} else {")
			e.block(s.Else)
		}
		e.line("}")
	case *TypeSwitchStmt:
		subj, _ := e.expr(s.Subject)
		e.line("switch %s := %s.(type) {", goLocal(s.Bind), subj)
		for _, cs := range s.Cases {
			names := make([]string, len(cs.Types))
			for i, q := range cs.Types {
				names[i] = q.String()
			}
			e.line("case %s:", strings.Join(names, ", "))
			e.block(cs.Body)
		}
		e.line("}")
	case *ExprStmt:
		if v, _ := e.expr(s.X); isTemp(v) {
			e.line("_ = %s", v)
		}
	}
}

func (e *emitter) block(b *Block) {
	e.depth++
	e.stmts(b.Stmts)
	e.depth--
}

func (e *emitter) ret(s *ReturnStmt) {
	f := e.top()
	if s.Value == nil {
		if f.fallible {
			e.line("return nil")
		} else {
			e.line("return")
		}
		return
	}
	in := e.c.Info[s.Value]
	v, err := e.expr(s.Value)
	switch {
	case in.fallible && f.result == "":
		e.line("return %s", err)
	case in.fallible:
		e.line("return %s, %s", v, err)
	case e.c.ErrorTypes[in.typ]:
		e.fail(v)
	case f.fallible:
		e.line("return %s, nil", v)
	default:
		e.line("return %s", v)
	}
}

// expr writes the statements an expression needs and returns Go text for its
// value ("" when it has none) and, when it can fail, the name of its error
// variable. Every call is bound to a temporary so evaluation order is kept.
func (e *emitter) expr(x Expr) (val, err string) {
	switch x := x.(type) {
	case *BasicLit:
		if x.Kind == tDuration {
			return e.duration(x.Text), ""
		}
		if x.Kind == tInt {
			// Typed, so a variadic any argument stays int64 on every GOARCH.
			return "int64(" + x.Text + ")", ""
		}
		// A string's value is what Go's rules decode from the source spelling
		// (checked, S108). Re-quoting it escapes bytes Go source cannot hold
		// raw: a byte order mark, NUL, invalid UTF-8.
		v, _ := strconv.Unquote(x.Text)
		return strconv.Quote(v), ""
	case *Ident:
		return goLocal(x.Name), ""
	case *Selector:
		v, _ := e.expr(x.X)
		return v + "." + x.Sel, ""
	case *Binary:
		l, _ := e.expr(x.L)
		r, _ := e.expr(x.R)
		return "(" + l + " " + x.Op + " " + r + ")", ""
	case *CompositeLit:
		elems := make([]string, len(x.Elems))
		for i, el := range x.Elems {
			v, _ := e.expr(el.Value)
			if x.Positional {
				elems[i] = v
			} else {
				elems[i] = el.Key + ": " + v
			}
		}
		return e.goType(x.Type) + "{" + strings.Join(elems, ", ") + "}", ""
	case *Call:
		return e.call(x)
	case *TryExpr:
		if ce, ok := x.X.(*CatchExpr); ok {
			return e.catch(ce), ""
		}
		v, err := e.expr(x.X)
		e.line("if %s != nil {", err)
		e.depth++
		e.fail(err)
		e.depth--
		e.line("}")
		return v, ""
	case *CatchExpr:
		return e.catch(x), ""
	}
	panic(fmt.Sprintf("emit: unchecked expression %T", x))
}

func (e *emitter) duration(text string) string {
	e.useTime = true
	i := strings.IndexFunc(text, func(r rune) bool { return r < '0' || r > '9' })
	unit := map[string]string{
		"ns": "Nanosecond", "us": "Microsecond", "ms": "Millisecond",
		"s": "Second", "m": "Minute", "h": "Hour",
	}[text[i:]]
	return text[:i] + " * time." + unit
}

// catch lowers to a type switch on the error. Its default arm passes on what
// no arm names: the rest of the row under try, and rt.Interrupted always. The
// checker has already decided which typed errors may pass, so try and a total
// catch lower the same way.
func (e *emitter) catch(x *CatchExpr) string {
	in := e.c.Info[x.X]
	v, err := e.expr(x.X)
	e.line("if %s != nil {", err)
	e.depth++
	e.line("switch %s.(type) {", err)
	for _, arm := range x.Arms {
		names := make([]string, len(arm.Types))
		for i, q := range arm.Types {
			names[i] = e.errorType(q.String())
		}
		e.line("case %s:", strings.Join(names, ", "))
		e.depth++
		av, _ := e.expr(arm.Value)
		switch {
		case in.typ != "":
			e.line("%s = %s", v, av)
		case isTemp(av):
			e.line("_ = %s", av)
		}
		e.depth--
	}
	e.line("default:")
	e.depth++
	e.fail(err)
	e.depth--
	e.line("}")
	e.depth--
	e.line("}")
	return v
}

func (e *emitter) errorType(name string) string {
	if name == expiredType {
		return "rt.Expired"
	}
	return name
}

// bindCall binds a call's results to temporaries.
func (e *emitter) bindCall(call string, in info) (val, err string) {
	switch {
	case in.fallible && in.typ != "":
		val, err = e.temp("v"), e.temp("e")
		e.line("%s, %s := %s", val, err, call)
	case in.fallible:
		err = e.temp("e")
		e.line("%s := %s", err, call)
	case in.typ != "":
		val = e.temp("v")
		e.line("%s := %s", val, call)
	default:
		e.line("%s", call)
	}
	return val, err
}

func (e *emitter) args(list []Expr) []string {
	out := make([]string, len(list))
	for i, a := range list {
		out[i], _ = e.expr(a)
	}
	return out
}

func (e *emitter) call(x *Call) (val, err string) {
	in := e.c.Info[x]
	switch fun := x.Fun.(type) {
	case *Ident:
		if fun.Name == "with" {
			return e.with(x, in)
		}
		args := append([]string{e.envPtr, "t__"}, e.args(x.Args)...)
		return e.bindCall(fun.Name+"("+strings.Join(args, ", ")+")", in)
	case *Selector:
		recv := fun.X.(*Ident).Name
		if e.c.Afters[x] {
			return e.after(x, in)
		}
		args := append([]string{"t__"}, e.args(x.Args)...)
		e.interruptCheck()
		return e.bindCall(e.envVal+"."+recv+"."+fun.Sel+"("+strings.Join(args, ", ")+")", in)
	}
	panic("emit: unchecked call")
}

func (e *emitter) interruptCheck() {
	if !e.top().fallible {
		e.line("t__.Check()")
		return
	}
	e.line("if t__.Stopped() {")
	e.depth++
	e.fail("rt.Interrupted")
	e.depth--
	e.line("}")
}

// with copies the env, sets the wire's fields and runs the block in a Go block
// against the copy. No closure: the block is inlined.
func (e *emitter) with(x *Call, in info) (val, err string) {
	val, err = e.declareResult(in)
	e.line("{")
	e.depth++
	savedVal, savedPtr := e.envVal, e.envPtr
	copyEnv := func() string {
		cp := e.temp("envc")
		if e.envPtr == "&Env__{}" {
			e.line("%s := Env__{}", cp)
		} else {
			e.line("%s := *%s", cp, e.envPtr)
		}
		return cp
	}
	switch w := x.Args[0].(type) {
	case *Ident:
		// A named wire is built by its own Go function, so the caller's local
		// names cannot capture its initializers.
		cp := copyEnv()
		e.line("%s(&%s, t__)", wireFunc(w.Name), cp)
		e.envVal, e.envPtr = cp, "&"+cp
	case *WireLit:
		// An empty wire provides nothing; the block keeps the enclosing env.
		if len(w.Entries) > 0 {
			cp := copyEnv()
			for _, en := range w.Entries {
				v, _ := e.expr(en.Value)
				e.line("%s.%s = %s", cp, en.Cap, v)
			}
			e.envVal, e.envPtr = cp, "&"+cp
		}
	}
	v, ev := e.blockLast(x.Block)
	e.envVal, e.envPtr = savedVal, savedPtr
	switch {
	case val != "" && err != "":
		e.line("%s, %s = %s, %s", val, err, v, ev)
	case val != "":
		e.line("%s = %s", val, v)
	case err != "":
		e.line("%s = %s", err, ev)
	case isTemp(v):
		e.line("_ = %s", v)
	}
	e.depth--
	e.line("}")
	return val, err
}

// declareResult declares the variables that carry a block's value and error out
// of a Go block.
func (e *emitter) declareResult(in info) (val, err string) {
	if in.typ != "" {
		val = e.temp("v")
		e.line("var %s %s", val, e.goType(in.typ))
	}
	if in.fallible {
		err = e.temp("e")
		e.line("var %s error", err)
	}
	return val, err
}

// blockLast writes all but the last statement of an expression block and
// returns the value and error of its last expression.
func (e *emitter) blockLast(b *Block) (val, err string) {
	e.stmts(b.Stmts[:len(b.Stmts)-1])
	last := b.Stmts[len(b.Stmts)-1]
	ls, ok := last.(*ExprStmt)
	if !ok {
		e.stmt(last)
		return "", ""
	}
	e.directive(ls.Pos)
	return e.expr(ls.X)
}

// after lowers timeout.After(d) { b } to rt.After with b as the child task's
// closure. It is the one Go func literal the emitter writes.
func (e *emitter) after(x *Call, in info) (val, err string) {
	d, _ := e.expr(x.Args[0])
	last := e.c.Info[x.Block.Stmts[len(x.Block.Stmts)-1].(*ExprStmt).X]
	call := fmt.Sprintf("rt.After(%s.Scheduler, t__, %s, func(t__ *rt.Task) (%s, error) {", e.envVal, d, e.goType(in.typ))
	if in.typ != "" {
		val, err = e.temp("v"), e.temp("e")
		e.line("%s, %s := %s", val, err, call)
	} else {
		err = e.temp("e")
		e.line("_, %s := %s", err, call)
	}
	e.depth++
	e.frames = append(e.frames, frame{result: in.typ, fallible: true, unit: in.typ == ""})
	res, rerr := e.blockLast(x.Block)
	e.frames = e.frames[:len(e.frames)-1]
	if last.typ == "" {
		if isTemp(res) {
			e.line("_ = %s", res)
		}
		res = "struct{}{}"
	}
	if !last.fallible {
		rerr = "nil"
	}
	e.line("return %s, %s", res, rerr)
	e.depth--
	e.line("})")
	return val, err
}
