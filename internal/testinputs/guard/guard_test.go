func TestMain(m *testing.M) { os.Exit(testinputs.Main(m)) }

const testinputsPath = "effra.local/prototype/internal/testinputs"

// exempt are the test packages that run without Main, with the reason.
var exempt = map[string]string{
	// Its end-to-end cases run observed test binaries, and an observed
	// process cannot observe its own children: a listener installed below
	// another hides the calls it takes from the outer one, which therefore
	// refuses the result. It keys its cache on the tools it runs by reading
	// testinputs.ToolDigest itself.
	"internal/testinputs": "runs observed test binaries itself",
}

// generateVariable, set to 1, makes TestEveryTestPackageIsObserved write a
// main_test.go into each test package that has no TestMain.
const generateVariable = "EFFRA_TESTINPUTS_GENERATE"

// TestEveryTestPackageIsObserved checks that every test package in the
// module has a TestMain, built on every platform, that calls
// testinputs.Main or testinputs.MainFunc. A package without one would cache
// its result on its own process's reads only, missing everything its
// subprocesses read.
func TestEveryTestPackageIsObserved(t *testing.T) {
	root := moduleRoot(t)
	generate := os.Getenv(generateVariable) == "1"
	for _, dir := range testDirectories(t, root) {
		rel, err := filepath.Rel(root, dir)
		if err != nil {
			t.Fatal(err)
		}
		rel = filepath.ToSlash(rel)
		if _, ok := exempt[rel]; ok {
			continue
		}
		pkg := inspect(t, dir)
		switch {
		case pkg.observed:
		case pkg.testMain != "":
			t.Errorf("%s: TestMain in %s does not call testinputs.Main or testinputs.MainFunc on every platform", rel, pkg.testMain)
		case generate:
			path := filepath.Join(dir, "main_test.go")
			if _, err := os.Lstat(path); err == nil {
				t.Errorf("%s: main_test.go exists without a TestMain; add one that calls testinputs.Main", rel)
				continue
			}
			if err := os.WriteFile(path, []byte(generated(pkg.name)), 0o644); err != nil {
				t.Fatal(err)
			}
			t.Logf("%s: wrote main_test.go", rel)
		default:
			t.Errorf("%s: no TestMain; run %s=1 go test ./internal/testinputs/guard to write one", rel, generateVariable)
		}
	}
	for rel := range exempt {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel))); err != nil {
			t.Errorf("exempt package %s: %v", rel, err)
		}
	}
}

// generated is the TestMain written into a package without one.
func generated(pkg string) string {
	return "// Code generated by internal/testinputs/guard. You may edit it; keep the\n" +
		"// call to testinputs.Main.\n\n" +
		"package " + pkg + "\n\n" +
		"import (\n\t\"os\"\n\t\"testing\"\n\n\t\"" + testinputsPath + "\"\n)\n\n" +
		"// TestMain runs the tests under observation, so the files and variables\n" +
		"// any process they start reads are inputs of Go's test cache.\n" +
		"func TestMain(m *testing.M) { os.Exit(testinputs.Main(m)) }\n"
}

func moduleRoot(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	for {
		if data, err := os.ReadFile(filepath.Join(dir, "go.mod")); err == nil {
			if !strings.Contains(string(data), "module effra.local/prototype\n") {
				t.Fatalf("%s/go.mod is not the effra.local/prototype module", dir)
			}
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("no go.mod above the test directory")
		}
		dir = parent
	}
}

// testDirectories returns the directories holding test files of every
// package `go test ./...` can run, under any build tags: the directories of
// the _test.go files in Git's index, minus those cmd/go's pattern skips (a
// directory named testdata or starting with "." or "_", and nested modules).
// It reads the index, not the tree: walking the tree would key this result
// on every directory's entries, build outputs included. A test package
// still untracked is checked once it is added. go list is not used: it
// omits a directory whose files are all excluded by build constraints.
func testDirectories(t *testing.T, root string) []string {
	t.Helper()
	listed := func(patterns ...string) []string {
		t.Helper()
		command := exec.Command("git", append([]string{"ls-files", "-z", "--cached", "--"}, patterns...)...)
		command.Dir = root
		output, err := command.Output()
		if err != nil {
			t.Fatalf("git ls-files %s: %v", strings.Join(patterns, " "), err)
		}
		return strings.FieldsFunc(string(output), func(r rune) bool { return r == 0 })
	}
	var nested []string
	for _, file := range listed("go.mod", "*/go.mod") {
		if dir := path.Dir(file); dir != "." {
			nested = append(nested, dir)
		}
	}
	var dirs []string
	for _, file := range listed("*_test.go") {
		dir := path.Dir(file)
		skipped := slices.ContainsFunc(strings.Split(dir, "/"), func(element string) bool {
			return element == "testdata" || strings.HasPrefix(element, ".") || strings.HasPrefix(element, "_")
		})
		inNested := slices.ContainsFunc(nested, func(module string) bool { return dir == module || strings.HasPrefix(dir, module+"/") })
		base := path.Base(file)
		if skipped || inNested || strings.HasPrefix(base, ".") || strings.HasPrefix(base, "_") {
			continue
		}
		if full := filepath.Join(root, filepath.FromSlash(dir)); !slices.Contains(dirs, full) {
			dirs = append(dirs, full)
		}
	}
	if len(dirs) == 0 {
		t.Fatal("git lists no test files")
	}
	return dirs
}

type testPackage struct {
	name     string // the package of the test files, preferring the internal one
	testMain string // the file declaring TestMain, if any
	observed bool   // that TestMain calls testinputs on every platform
}

func inspect(t *testing.T, dir string) testPackage {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var pkg testPackage
	fset := token.NewFileSet()
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, "_test.go") || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution|parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		if pkg.name == "" || !strings.HasSuffix(file.Name.Name, "_test") {
			pkg.name = file.Name.Name
		}
		if testMain(file) != nil {
			pkg.testMain = name
			pkg.observed = everyPlatform(name, file) && observes(file)
		}
	}
	return pkg
}

func testMain(file *ast.File) *ast.FuncDecl {
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv == nil && fn.Name.Name == "TestMain" {
			return fn
		}
	}
	return nil
}

// observes reports whether the file's TestMain calls testinputs.Main or
// testinputs.MainFunc. It accepts a call anywhere in the body, a dead or
// conditional branch included: the guard catches a package that forgot
// observation, not one written to evade it.
func observes(file *ast.File) bool {
	local := ""
	for _, spec := range file.Imports {
		if path, err := strconv.Unquote(spec.Path.Value); err == nil && path == testinputsPath {
			local = "testinputs"
			if spec.Name != nil {
				local = spec.Name.Name
			}
		}
	}
	fn := testMain(file)
	if local == "" || local == "_" || local == "." || fn == nil || fn.Body == nil {
		return false
	}
	found := false
	ast.Inspect(fn.Body, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return !found
		}
		if selector, ok := call.Fun.(*ast.SelectorExpr); ok {
			if x, ok := selector.X.(*ast.Ident); ok && x.Name == local && (selector.Sel.Name == "Main" || selector.Sel.Name == "MainFunc") {
				found = true
			}
		}
		return !found
	})
	return found
}

// everyPlatform reports whether a test file builds on every platform: it has
// no //go:build line and no _GOOS or _GOARCH name suffix.
func everyPlatform(name string, file *ast.File) bool {
	for _, group := range file.Comments {
		if group.Pos() > file.Package {
			break
		}
		for _, comment := range group.List {
			if constraint.IsGoBuild(comment.Text) || constraint.IsPlusBuild(comment.Text) {
				return false
			}
		}
	}
	parts := strings.Split(strings.TrimSuffix(name, "_test.go"), "_")
	for _, part := range parts[1:] {
		if slices.Contains(platformWords, part) {
			return false
		}
	}
	return true
}

// platformWords are the GOOS and GOARCH values a file name suffix can name
// (go/build's syslist).
var platformWords = []string{
	"aix", "android", "darwin", "dragonfly", "freebsd", "hurd", "illumos", "ios", "js", "linux", "nacl", "netbsd", "openbsd", "plan9", "solaris", "wasip1", "windows", "zos",
	"386", "amd64", "amd64p32", "arm", "armbe", "arm64", "arm64be", "loong64", "mips", "mipsle", "mips64", "mips64le", "mips64p32", "mips64p32le", "ppc", "ppc64", "ppc64le", "riscv", "riscv64", "s390", "s390x", "sparc", "sparc64", "wasm",
}

// TestObserves checks the recognizer on the shapes a TestMain takes.
func TestObserves(t *testing.T) {
	for _, c := range []struct {
		name, source string
		want         bool
	}{
		{"main_test.go", "package p\nimport (\"os\"; \"testing\"; \"" + testinputsPath + "\")\nfunc TestMain(m *testing.M) { os.Exit(testinputs.Main(m)) }", true},
		{"main_test.go", "package p\nimport (\"os\"; \"testing\"; ti \"" + testinputsPath + "\")\nfunc TestMain(m *testing.M) { code := ti.MainFunc(m, func() int { return m.Run() }); os.Exit(code) }", true},
		{"main_test.go", "package p\nimport (\"os\"; \"testing\"; \"" + testinputsPath + "\")\nfunc TestMain(m *testing.M) { _ = testinputs.ToolDigest; os.Exit(m.Run()) }", false},
		{"main_test.go", "package p\nimport (\"os\"; \"testing\")\nfunc TestMain(m *testing.M) { os.Exit(m.Run()) }", false},
		{"main_test.go", "package p\nimport (\"os\"; \"testing\"; \"other/testinputs\")\nfunc TestMain(m *testing.M) { os.Exit(testinputs.Main(m)) }", false},
		{"main_test.go", "//go:build linux\n\npackage p\nimport (\"os\"; \"testing\"; \"" + testinputsPath + "\")\nfunc TestMain(m *testing.M) { os.Exit(testinputs.Main(m)) }", false},
		{"main_linux_test.go", "package p\nimport (\"os\"; \"testing\"; \"" + testinputsPath + "\")\nfunc TestMain(m *testing.M) { os.Exit(testinputs.Main(m)) }", false},
		{"main_amd64_test.go", "package p\nimport (\"os\"; \"testing\"; \"" + testinputsPath + "\")\nfunc TestMain(m *testing.M) { os.Exit(testinputs.Main(m)) }", false},
	} {
		file, err := parser.ParseFile(token.NewFileSet(), c.name, c.source, parser.SkipObjectResolution|parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		if got := everyPlatform(c.name, file) && observes(file); got != c.want {
			t.Errorf("%s:\n%s\nobserved %v, want %v", c.name, c.source, got, c.want)
		}
	}
	if file, err := parser.ParseFile(token.NewFileSet(), "main_test.go", generated("p_test"), parser.SkipObjectResolution|parser.ParseComments); err != nil || !observes(file) {
		t.Fatalf("the generated TestMain is not recognized: %v", err)
	}
}
